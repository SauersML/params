"""Pretraining-mean proxies for models whose means are not released (their dense baselines).

Their models trained on GPT-4-base-generated Python (unreleased), with files joined by "<|endoffile|>" and 256-token
contexts. The proxy is codeparrot-clean shard 53 (disjoint from shard 54, which the tasks come from), joined the same
way and cut into 256-token windows. The proxy is checked on csp_yolo2, whose means are released.

python means.py gao MODEL [--windows 2000] [--device mps]        -> models/MODEL/mean_proxy_codeparrot.pt
python means.py compare MODEL                                    released vs proxy, per site
"""
import argparse
import gzip
import json
import os

import torch

import nodes as N

ROOT = N.ROOT
SHARD = f"{ROOT}/corpus/file-000000000053.json.gz"


def windows(model, n: int, T: int = 256) -> list:
    buf, out = [], []
    with gzip.open(SHARD, "rt") as f:
        for line in f:
            d = json.loads(line)
            if d.get("autogenerated"):
                continue
            buf += model.tokenize(d["content"] + "<|endoffile|>")
            while len(buf) >= T:
                out.append(buf[:T])
                buf = buf[T:]
                if len(out) >= n:
                    return out
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd")
    ap.add_argument("model")
    ap.add_argument("--windows", type=int, default=2000)
    ap.add_argument("--device", default="mps")
    ap.add_argument("--bs", type=int, default=4)
    a = ap.parse_args()
    out = f"{ROOT}/models/{a.model}/mean_proxy_codeparrot.pt"
    if a.cmd == "gao":
        model = N.GaoModel(a.model, a.device)
        rows = windows(model, a.windows)
        mu = N.accumulate_means(model, rows, bs=a.bs)
        torch.save(mu, out)
        print("saved", out, len(rows), "windows")
    elif a.cmd == "compare":
        rel = torch.load(f"{ROOT}/models/{a.model}/mean_baseline_pretrain.pt", weights_only=True)
        prox = torch.load(out, weights_only=True)
        for s in prox:
            r, p = rel[s].float(), prox[s].float()
            c = torch.corrcoef(torch.stack([r, p]))[0, 1]
            print(f"{s:22s} corr {float(c):.3f}  |rel| {float(r.abs().mean()):.4f}  |prox-rel| {float((p - r).abs().mean()):.4f}")


if __name__ == "__main__":
    main()
